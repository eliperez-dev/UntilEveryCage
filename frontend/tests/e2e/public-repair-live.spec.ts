import { expect, test } from '@playwright/test';

test('public filters and full facility facts work against an approved real release', async ({ page }) => {
  test.skip(!process.env.UEC_PUBLIC_REPAIR, 'Requires the configured approved release API and public build.');
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.name));
  const manifest = await (await page.request.get('/api/v2/releases/manifest?profile=official')).json();
  const release = manifest.data.release_id as string;
  const list = async (filters: Record<string, string> = {}) => {
    const response = await page.request.get(`/api/v2/locations?${new URLSearchParams({ profile: 'official', release_id: release, limit: '100', ...filters })}`);
    expect(response.ok()).toBe(true);
    return response.json();
  };
  const netherlands = await list({ country_code: 'NL' });
  expect(netherlands.meta.total_count > 0).toBe(true);
  expect(netherlands.data.every((row: { country_code: string }) => row.country_code === 'NL')).toBe(true);
  const fsis = await list({ source_id: 'us.fsis', category_keys: 'processing_and_preparation' });
  expect(fsis.meta.total_count > 0).toBe(true);
  expect(fsis.data.every((row: { provenance_source_id: string; taxonomy_primary_categories: string[] }) => row.provenance_source_id === 'us.fsis' && row.taxonomy_primary_categories.includes('processing_and_preparation'))).toBe(true);
  const feed = await (await page.request.get(`/api/v2/map/feed?${new URLSearchParams({ profile: 'official', release_id: release, format: 'compact' })}`)).json();
  expect(feed.data.features.some((row: unknown[]) => row[7] === 'NL')).toBe(true);
  // Real values stay in memory. Assertions expose booleans, never source rows.
  const row = fsis.data[0];
  const detailResponse = await page.request.get(`/api/v2/locations/${row.facility_id}?${new URLSearchParams({ profile: 'official', release_id: release })}`);
  expect(detailResponse.ok()).toBe(true);
  const detail = (await detailResponse.json()).data;
  await page.goto(`/#/map?${new URLSearchParams({ release_id: release, selected: row.facility_id, list: 'closed' })}`);
  const panel = page.locator('.reading-sheet[aria-label="Record evidence"]');
  await expect(panel).toBeVisible({ timeout: 60_000 });
  await expect.poll(() => panel.evaluate((element, expected) => element.textContent?.includes(expected.name) && element.textContent.includes(expected.source), { name: detail.canonical_name, source: detail.provenance_source_name })).toBe(true);
  await expect(page.getByText('Local V2 detail response was rejected.', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Close record detail' }).click();
  await page.getByRole('button', { name: /Search map/ }).click();
  await page.locator('details.filters summary').click();
  const countryGroup = page.locator('fieldset').filter({ has: page.locator('legend', { hasText: /^Country$/ }) });
  const countryResponse = page.waitForResponse(response => response.url().includes('/api/v2/locations?') && new URL(response.url()).searchParams.get('country_code') === 'NL');
  await countryGroup.getByRole('checkbox', { name: /^Netherlands/ }).check({ timeout: 30_000 });
  expect((await countryResponse).ok()).toBe(true);
  await expect(page.locator('.result-status')).toContainText(`${netherlands.meta.total_count} matching`);
  const cleared = page.waitForResponse(response => response.url().includes('/api/v2/locations?') && !new URL(response.url()).searchParams.has('country_code'));
  await page.getByRole('button', { name: 'Clear all filters', exact: true }).click();
  expect((await cleared).ok()).toBe(true);
  const sources = page.locator('fieldset').filter({ has: page.locator('legend', { hasText: /^Source$/ }) });
  await expect(sources.getByRole('checkbox')).not.toHaveCount(0);
  const facets = await (await page.request.get(`/api/v2/discovery/facets?${new URLSearchParams({ profile: 'official', release_id: release })}`)).json();
  const sourceIndex = facets.dimensions.source_id.findIndex((facet: { value: string }) => facet.value === 'us.fsis');
  expect(sourceIndex >= 0).toBe(true);
  const sourceResponse = page.waitForResponse(response => response.url().includes('/api/v2/locations?') && new URL(response.url()).searchParams.get('source_id') === 'us.fsis');
  await sources.getByRole('checkbox').nth(sourceIndex).check();
  expect((await sourceResponse).ok()).toBe(true);
  const categoryResponse = page.waitForResponse(response => response.url().includes('/api/v2/locations?') && new URL(response.url()).searchParams.get('source_id') === 'us.fsis' && new URL(response.url()).searchParams.get('category_keys') === 'processing_and_preparation');
  await page.getByRole('checkbox', { name: 'Processing and preparation', exact: true }).check();
  expect((await categoryResponse).ok()).toBe(true);
  await expect(page.locator('.result-status')).toContainText(`${fsis.meta.total_count} matching`);
  await page.goto(`/#/records/${row.facility_id}?release_id=${encodeURIComponent(release)}`);
  await expect(page.locator('.public-record h1')).toBeVisible({ timeout: 30_000 });
  expect(await page.locator('.public-record').evaluate((element, name) => element.textContent?.includes(name), detail.canonical_name)).toBe(true);
  await page.getByRole('navigation', { name:'Primary' }).getByRole('link', { name:'Map', exact:true }).click();
  if (await page.getByRole('button', { name:'Search map' }).count()) await page.getByRole('button', { name:'Search map' }).click();
  const filters = page.locator('details.filters');
  if (await filters.getAttribute('open') === null) await filters.locator('summary').click();
  const country = page.locator('fieldset').filter({ has:page.locator('legend', { hasText:/^Country$/ }) });
  await country.getByRole('checkbox', { name:/^Netherlands/ }).check();
  await expect(page.locator('.result-status')).toContainText(netherlands.meta.total_count + ' matching', { timeout:30_000 });
  await expect(page.getByText(/Results are eligible public facility projection rows/)).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Make Facility details wider' })).toHaveCount(0);
  expect(errors).toEqual([]);
});
